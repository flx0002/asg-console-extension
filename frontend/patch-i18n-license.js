#!/usr/bin/env node
/*
 * patch-i18n-license.js
 * 幂等补丁：为产品级「授权管理」拆页写入 console fork 的 translation.json
 *   1) menu.licenseManagement（授权管理 / License Management）
 *   2) license.* 全量键（状态/类型/公司 + 功能位表 + 导入·更新授权措辞）
 *   3) 删除 aiKb.pageHint（#4 去文案）
 *   4) 改写 aiKb.unauthorizedHint（去「激活」措辞，改「更新授权」）
 * 用法: node patch-i18n-license.js <translation.json 路径> <locale: zh-CN|en-US>
 * 仅当内容有变化时回写（2 空格缩进 + 末尾换行，与 inject.sh 合并格式一致）。
 */
const fs = require('fs');

const [, , target, locale] = process.argv;
if (!target || !locale) {
  console.error('usage: node patch-i18n-license.js <translation.json> <zh-CN|en-US>');
  process.exit(2);
}

const I18N = {
  'zh-CN': {
    menuLicenseManagement: '授权管理',
    license: {
      status: '授权状态',
      statusValid: '有效',
      statusExpired: '已过期',
      statusInvalid: '无效',
      statusAbsent: '未授权',
      sectionInfo: '授权信息',
      sectionFeatures: '功能位',
      featureName: '功能位',
      featureIssuedAt: '签发时间',
      featureExpiresAt: '过期时间',
      featureStatus: '有效',
      type: '授权类型',
      typeFormal: '正式（永久）',
      typeTemporary: '临时',
      company: '授权公司',
      deviceFp: '本机设备ESN',
      copy: '复制',
      copied: '已复制到剪贴板',
      import: '导入授权文件',
      update: '更新授权',
      importConfirmTitle: '确认导入该授权文件？',
      importConfirmContent: '授权文件由厂商授权工具生成，导入后将校验并绑定本机设备指纹。',
      importSuccess: '授权导入成功',
      updateSuccess: '授权更新成功',
      actionFailed: '操作失败',
      forever: '永久',
      yes: '是',
      no: '否',
      noFeatures: '暂无功能位',
      feature: {
        ai_kb_update: 'AI分类知识库更新',
      },
    },
    unauthorizedHint: '当前无有效授权，无法更新知识库。请先在「授权管理」中导入或更新授权后再更新，或回滚到历史版本。',
  },
  'en-US': {
    menuLicenseManagement: 'License Management',
    license: {
      status: 'License Status',
      statusValid: 'Valid',
      statusExpired: 'Expired',
      statusInvalid: 'Invalid',
      statusAbsent: 'Not Licensed',
      sectionInfo: 'License Information',
      sectionFeatures: 'Feature Entitlements',
      featureName: 'Feature',
      featureIssuedAt: 'Issued At',
      featureExpiresAt: 'Expires At',
      featureStatus: 'Active',
      type: 'License Type',
      typeFormal: 'Formal (Permanent)',
      typeTemporary: 'Temporary',
      company: 'Licensed To',
      deviceFp: 'Device ESN',
      copy: 'Copy',
      copied: 'Copied to clipboard',
      import: 'Import License File',
      update: 'Update License',
      importConfirmTitle: 'Import this license file?',
      importConfirmContent: 'The license file is generated by the vendor tool; it will be verified and bound to this device fingerprint.',
      importSuccess: 'License imported',
      updateSuccess: 'License updated',
      actionFailed: 'Action failed',
      forever: 'Never',
      yes: 'Yes',
      no: 'No',
      noFeatures: 'No feature entitlements',
      feature: {
        ai_kb_update: 'AI Classification KB Update',
      },
    },
    unauthorizedHint: 'No valid license. Knowledge base update is disabled. Import or update the license under "License Management" first, or roll back to a previous version.',
  },
};

const spec = I18N[locale];
if (!spec) {
  console.error(`unsupported locale: ${locale}`);
  process.exit(2);
}

const raw = fs.readFileSync(target, 'utf8');
const json = JSON.parse(raw);
let changed = false;

// 1) menu.licenseManagement
if (!json.menu || typeof json.menu !== 'object') json.menu = {};
if (json.menu.licenseManagement !== spec.menuLicenseManagement) {
  json.menu.licenseManagement = spec.menuLicenseManagement;
  changed = true;
}

// 2) license.* 全量覆盖
if (JSON.stringify(json.license) !== JSON.stringify(spec.license)) {
  json.license = spec.license;
  changed = true;
}

// 3) 删除 aiKb.pageHint
if (json.aiKb && Object.prototype.hasOwnProperty.call(json.aiKb, 'pageHint')) {
  delete json.aiKb.pageHint;
  changed = true;
}

// 4) 改写 aiKb.unauthorizedHint（去「激活」措辞）
if (json.aiKb && json.aiKb.unauthorizedHint !== spec.unauthorizedHint) {
  json.aiKb.unauthorizedHint = spec.unauthorizedHint;
  changed = true;
}

if (changed) {
  fs.writeFileSync(target, JSON.stringify(json, null, 2) + '\n');
  console.log(`  ✓ patched i18n (${locale}): ${target}`);
} else {
  console.log(`  SKIP: i18n already up to date (${locale})`);
}
