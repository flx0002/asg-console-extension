const spec = I18N[locale];
if (!spec) {
  console.error(`unsupported locale: ${locale}`);
  process.exit(2);
}

const raw = fs.readFileSync(target, 'utf8');
const json = JSON.parse(raw);
let changed = false;

// 1) menu.licenseManagement / menu.kbOnlineSetting
if (!json.menu || typeof json.menu !== 'object') json.menu = {};
if (json.menu.licenseManagement !== spec.menuLicenseManagement) {
  json.menu.licenseManagement = spec.menuLicenseManagement;
  changed = true;
}
if (json.menu.kbOnlineSetting !== spec.menuKbOnlineSetting) {
  json.menu.kbOnlineSetting = spec.menuKbOnlineSetting;
  changed = true;
}

// 1b) kbSetting.* 全量覆盖（KB 在线更新系统配置页）
if (JSON.stringify(json.kbSetting) !== JSON.stringify(spec.kbSetting)) {
  json.kbSetting = spec.kbSetting;
  changed = true;
}

// 2) license.* 全量覆盖
if (JSON.stringify(json.license) !== JSON.stringify(spec.license)) {
  json.license = spec.license;
  changed = true;
}

// 3) 删除 aiKb.pageHint
if (json.aiKb && Object.prototype.hasOwnProperty.call(json.aiKb, 'pageHint')) {
  delete json.aiKb.pageHint;
  changed = true;
}

// 3b) 删除 aiKb.importBundleConfirmContent（离线导入确认框去内部机制措辞；页已不引用该键）
if (json.aiKb && Object.prototype.hasOwnProperty.call(json.aiKb, 'importBundleConfirmContent')) {
  delete json.aiKb.importBundleConfirmContent;
  changed = true;
}

// 4) 改写 aiKb.unauthorizedHint（去「激活」措辞）
if (json.aiKb && json.aiKb.unauthorizedHint !== spec.unauthorizedHint) {
  json.aiKb.unauthorizedHint = spec.unauthorizedHint;
  changed = true;
}

// 5) 补充 aiKb 新增键（#1 去重提示 + #3 网关同步徽标），只增量写入不覆盖其它键
if (!json.aiKb || typeof json.aiKb !== 'object') json.aiKb = {};
for (const [k, v] of Object.entries(spec.aiKbAdd || {})) {
  if (json.aiKb[k] !== v) {
    json.aiKb[k] = v;
    changed = true;
  }
}

if (changed) {
  fs.writeFileSync(target, JSON.stringify(json, null, 2) + '\n');
  console.log(`  ✓ patched i18n (${locale}): ${target}`);
} else {
  console.log(`  SKIP: i18n already up to date (${locale})`);
}
